/**
 * Validates whether an order can transition from currentStatus to targetStatus
 * @param {string} currentStatus
 * @param {string} targetStatus
 * @returns {boolean}
 */
export const canTransitionOrder = (currentStatus, targetStatus) => {
  if (!currentStatus || !targetStatus) return false;
  const allowedNext = ORDER_STATE_TRANSITIONS[currentStatus] || [];
  return allowedNext.includes(targetStatus);
};

/**
 * Returns list of allowed next statuses for a given order status
 * @param {string} currentStatus
 * @returns {string[]}
 */
export const getAllowedTransitions = (currentStatus) => {
  return ORDER_STATE_TRANSITIONS[currentStatus] || [];
};

export const canRoleTransitionOrder = (role, targetStatus) => {
  if (["SUPER_ADMIN", "ADMIN", "OPERATIONS_MANAGER"].includes(role)) return true;
  const roleTransitions = {
    WAREHOUSE_MANAGER: [
      ORDER_STATUS.INVENTORY_CHECK,
      ORDER_STATUS.WAREHOUSE_ALLOCATION,
      ORDER_STATUS.PICK_LIST_CREATED,
      ORDER_STATUS.PICKING,
      ORDER_STATUS.PICKED,
      ORDER_STATUS.PACKING,
      ORDER_STATUS.PACKED,
      ORDER_STATUS.SHIPMENT_CREATED,
      ORDER_STATUS.CARRIER_ASSIGNED,
      ORDER_STATUS.DISPATCHED,
      ORDER_STATUS.IN_TRANSIT,
      ORDER_STATUS.OUT_FOR_DELIVERY,
      ORDER_STATUS.DELIVERED,
      ORDER_STATUS.RETURN_RECEIVED,
      ORDER_STATUS.RETURN_INSPECTED,
    ],
    PICKER: [ORDER_STATUS.PICKING, ORDER_STATUS.PICKED],
    PACKER: [ORDER_STATUS.PACKING, ORDER_STATUS.PACKED],
  };
  return (roleTransitions[role] || []).includes(targetStatus);
};
