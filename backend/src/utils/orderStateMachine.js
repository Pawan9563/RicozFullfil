/**
 * Order Lifecycle State Machine
 *
 * Primary Lifecycle:
 * ORDER_CREATED -> CONFIRMED -> INVENTORY_CHECK -> WAREHOUSE_ALLOCATION ->
 * PICK_LIST_CREATED -> PICKING -> PICKED -> PACKING -> PACKED ->
 * SHIPMENT_CREATED -> CARRIER_ASSIGNED -> DISPATCHED -> IN_TRANSIT ->
 * OUT_FOR_DELIVERY -> DELIVERED
 *
 * Alternate & Terminal Paths:
 * - CANCELLED (allowed prior to DISPATCHED)
 * - FAILED_DELIVERY (from OUT_FOR_DELIVERY)
 * - RETURN_REQUESTED -> RETURN_APPROVED -> PICKUP_SCHEDULED -> RETURN_IN_TRANSIT ->
 *   RETURN_RECEIVED -> RETURN_INSPECTED -> RETURN_REFUNDED / RETURN_REPLACED
 */

